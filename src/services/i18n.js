// Reactive current language
const currentLang = ref('en')

// Translation function with interpolation support: t('key', { name: 'John' })
function t(key, params = {}) {
  const dict = translations[currentLang.value] || translations.en
  let str = dict[key] !== undefined ? dict[key] : (translations.en[key] !== undefined ? translations.en[key] : key)
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  }
  return str
}

// Set the current interface language
function setLang(code) {
  if (translations[code]) {
    currentLang.value = code
  }
}

// Get the current language code
function getLang() {
  return currentLang.value
}

// Map a language code to the full name used by the AI service
function llmLangName(code) {
  return LLM_LANGUAGE_NAMES[code] || 'English'
}

